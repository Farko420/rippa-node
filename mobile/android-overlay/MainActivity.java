package com.rippaadventures.node;

import android.os.Bundle;
import android.webkit.WebView;

import com.getcapacitor.BridgeActivity;

/**
 * THE LAUNCHER ACTIVITY — registers the native plugin and the WebView bridge.
 *
 * WHY THIS FILE IS IN THE OVERLAY RATHER THAN LEFT TO CAPACITOR. `npx cap add
 * android` generates a MainActivity that extends BridgeActivity and does nothing,
 * and the overlay is copied in after generation by scripts/package-apk.mjs — so
 * this body survives every Capacitor upgrade without a merge conflict, exactly
 * like the manifest that names this very class.
 *
 * WHY RippaNodePlugin MUST BE REGISTERED HERE, EXPLICITLY.
 *
 * This was the second half of the bug behind "Native bridge unavailable".
 * Capacitor only auto-registers plugins that appear in
 * `app/src/main/assets/capacitor.plugins.json`, and that file is GENERATED by
 * `cap sync` from the npm packages in mobile/package.json — which lists only
 * @capacitor/device. RippaNodePlugin lives in the app's own source set, so it is
 * not in that manifest, `PluginManager.loadPluginClasses()` never sees it, and
 * the bridge is built WITHOUT it. `window.Capacitor.Plugins.RippaNode` was
 * therefore undefined on every device, no matter what the worker looked for.
 *
 * `registerPlugin` only ADDS to the Bridge.Builder, and the builder is consumed
 * by `load()`, which BridgeActivity.onCreate() calls. So the call MUST happen
 * BEFORE `super.onCreate()` — registering afterwards would add a plugin to a
 * builder nobody reads again, which looks correct and does nothing. This is the
 * same ordering trap as a Service needing startForeground() immediately.
 *
 * WHY THE BRIDGE IS ATTACHED AFTER THE SUPER CALL. `addJavascriptInterface` is a
 * WebView method, and in a Capacitor app the WebView belongs to the bridge rather
 * than to this Activity. It only exists once `super.onCreate()` has run and
 * BridgeActivity.load() has built it — which is why it is registered there and
 * null-checked, rather than in `load()` or a static initialiser.
 *
 * Registering once means the interface survives every later page load: the
 * WebView object is long-lived and re-registering per load would only duplicate
 * the same object under the same name.
 */
public class MainActivity extends BridgeActivity {

    @Override
    protected void onCreate(Bundle savedInstanceState) {
        // BEFORE super.onCreate(): the builder this feeds is consumed by the
        // load() call inside it. See the note above.
        registerPlugin(RippaNodePlugin.class);

        super.onCreate(savedInstanceState);

        if (getBridge() == null || getBridge().getWebView() == null) {
            // BridgeActivity falls back to a "no webview" layout when its own
            // layout fails to inflate, leaving the bridge null. There is no WebView
            // to attach to in that case, and that is not worth crashing over.
            android.util.Log.w("RippaNode", "No Capacitor WebView; mobileBridge not attached.");
            return;
        }

        WebView webView = getBridge().getWebView();
        webView.addJavascriptInterface(new MobileBridge(this, webView), MobileBridge.NAME);
        android.util.Log.i("RippaNode", "mobileBridge attached (updater + version reporting).");

        /*
          THE SERVICE RE-ARMS ITSELF ON EVERY LAUNCH.

          An operator who force-stops the app, or who installs an update over the
          old APK, arrives here with no service running — the boot receiver only
          fires on BOOT_COMPLETED/MY_PACKAGE_REPLACED, not on a manual tap. Without
          this, opening the app would silently re-join the swarm unprotected and
          the tablet would die overnight again.

          Only when the service is NOT already running: re-arming an existing one
          is harmless but pointless, and skipping it keeps the operator's explicit
          "stop it" choice intact across an ordinary app switch.
        */
        if (!RippaNodeService.isRunning()) {
            try {
                RippaNodeService.start(this, null, null);
                android.util.Log.i("RippaNode", "Foreground service (re)armed on activity create.");
            } catch (Exception error) {
                android.util.Log.w(
                        "RippaNode", "Could not arm the foreground service: " + error.getMessage());
            }
        }
    }
}